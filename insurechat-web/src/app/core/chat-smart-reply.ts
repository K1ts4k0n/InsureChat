/**
 * Smart Client-Side Insurance Advisor Engine (Fallback สำหรับ GitHub Pages / Demo Mode)
 * ช่วยตอบคำถามลูกค้าอย่างเป็นมืออาชีพ มีความรู้ประกันภัยครบถ้วน และเป็นธรรมชาติ
 */

export interface SmartReplyResult {
  reply: string;
  suggestions: string[];
}

export function getSmartInsuranceReply(
  userText: string,
  carBrand?: string,
  carModel?: string,
  carYear?: number
): SmartReplyResult {
  const q = (userText || '').toLowerCase().trim();
  const car = [carBrand, carModel, carYear ? `ปี ${carYear}` : ''].filter(Boolean).join(' ');
  const carPrefix = car ? `สำหรับรถ **${car}** ` : '';

  // 1. ทักทาย / เริ่มต้น
  if (q.includes('หวัดดี') || q.includes('สวัส') || q.includes('hello') || q.includes('hi') || q === 'ดี' || q.includes('สอบถาม')) {
    return {
      reply: `สวัสดีค่ะ ยินดีต้อนรับสู่ InsureChat นะคะ 😊\n\n${carPrefix}น้องยินดีช่วยแนะนำและเปรียบเทียบแผนประกันภัยที่คุ้มค่าที่สุดให้ค่ะ\n\nต้องการให้ช่วยคัดเลือกแผนแบบไหนเป็นพิเศษไหมคะ เช่น:\n• ประกันชั้น 1 ซ่อมห้าง (คุ้มครองสูงสุด ไร้กังวล)\n• ประกันชั้น 1 ซ่อมอู่ (เบี้ยประหยัด คุ้มค่า)\n• ประกันชั้น 2+ (คุ้มครองรถชนรถ หาย ไฟไหม้ น้ำท่วม ราคาสบายกระเป๋า)\n\nแจ้งงบประมาณหรือสิ่งที่กังวลได้เลยนะคะ`,
      suggestions: ['สนใจประกันชั้น 1 ซ่อมห้าง', 'สนใจประกันชั้น 1 ซ่อมอู่', 'สนใจประกัน 2+ สุดคุ้ม', 'เช็คเบี้ยที่ถูกที่สุด']
    };
  }

  // 2. ประกันชั้น 1
  if (q.includes('ชั้น 1') || q.includes('ชั้น1') || q.includes('ประเภท 1') || q.includes('ประเภท1') || q === '1') {
    return {
      reply: `${carPrefix}ขอแนะนำ **ประกันภัยรถยนต์ชั้น 1** ค่ะ ถือเป็นแผนที่ครอบคลุมและอุ่นใจที่สุด:\n\n` +
        `🛡️ **จุดเด่นความคุ้มครอง:**\n` +
        `• คุ้มครองการชนทุกกรณี ทั้งมีคู่กรณีและไม่มีคู่กรณี (เช่น เฉี่ยวเสา หินดีด ถอยชนกระถางต้นไม้)\n` +
        `• คุ้มครองภัยธรรมชาติ น้ำท่วม ไฟไหม้ โจรกรรม และลมพายุ\n` +
        `• คุ้มครองชีวิต ร่างกาย และทรัพย์สินของบุคคลภายนอก วงเงินสูง\n` +
        `• มีค่ารักษาพยาบาลและประกันตัวผู้ขับขี่\n\n` +
        `💰 **ช่วงเบี้ยโดยประมาณ:**\n` +
        `• ซ่อมห้าง (ศูนย์บริการ): เริ่มต้นประมาณ 17,500 - 21,000 บาท/ปี\n` +
        `• ซ่อมอู่มาตรฐาน: เริ่มต้นประมาณ 14,000 - 17,000 บาท/ปี\n\n` +
        `สนใจเปรียบเทียบระหว่างซ่อมห้างกับซ่อมอู่ หรือต้องการใบเสนอราคาไหมคะ?`,
      suggestions: ['ซ่อมห้างกับซ่อมอู่ต่างกันยังไง?', 'ต้องการขอใบเสนอราคา', 'มีผ่อน 0% ไหม?', 'ดูแผน 2+ เทียบ']
    };
  }

  // 3. ประกัน 2+
  if (q.includes('2+') || q.includes('2 บวก') || q.includes('สองบวก') || q.includes('ชั้น 2') || q.includes('2plus')) {
    return {
      reply: `${carPrefix}ขอแนะนำ **ประกันภัยรถยนต์ 2+ (สองบวก)** ค่ะ เป็นแผนยอดฮิตสำหรับคนที่ต้องการความคุ้มครองหลักในราคาประหยัด:\n\n` +
        `✅ **สิ่งที่คุ้มครอง:**\n` +
        `• รถชนกับยานพาหนะทางบก (ซ่อมทั้งรถเราและรถคู่กรณี)\n` +
        `• คุ้มครองรถสูญหาย และไฟไหม้\n` +
        `• คุ้มครองน้ำท่วม (เกือบทุกแพ็กเกจมีให้)\n\n` +
        `❌ **สิ่งที่ไม่คุ้มครอง:** ไม่คุ้มครองการชนที่ไม่มีคู่กรณี (เช่น ชนเสาไฟฟ้า เบียดกำแพง คว่ำเอง)\n\n` +
        `💵 **เบี้ยประกัน:** เริ่มต้นเพียง **7,500 - 8,900 บาท/ปี** เท่านั้นค่ะ คุ้มค่ามากสำหรับผู้ขับขี่ที่ขับชำนาญแล้ว`,
      suggestions: ['ดูแผน 2+ ที่มีน้ำท่วม', 'เปรียบเทียบบริษัทประกัน', 'สนใจสมัครแผน 2+']
    };
  }

  // 4. ประกัน 3+ / ชั้น 3
  if (q.includes('3+') || q.includes('3 บวก') || q.includes('สามบวก') || q.includes('ชั้น 3') || q === '3') {
    return {
      reply: `${carPrefix}สำหรับแผน **3+ และชั้น 3** เหมาะสำหรับรถที่ใช้งานน้อย หรือเน้นประหยัดงบค่ะ:\n\n` +
        `• **ชั้น 3+**: คุ้มครองรถชนรถ (มีคู่กรณี) ซ่อมทั้งรถเราและคู่กรณี เบี้ยเริ่มต้นเพียง **5,500 - 6,500 บาท/ปี** (ไม่คุ้มครองรถหาย/ไฟไหม้)\n` +
        `• **ชั้น 3 ธรรมดา**: ซ่อมเฉพาะรถคู่กรณี (ไม่ซ่อมรถเรา) เบี้ยเริ่มต้นเพียง **1,900 - 2,800 บาท/ปี**\n\n` +
        `ต้องการให้ทำใบเสนอราคา 3+ หรือดูแผน 2+ เพิ่มเติมไหมคะ?`,
      suggestions: ['ดูแผน 3+ เพิ่มเติม', 'เปรียบเทียบ 2+ กับ 3+', 'ขอคำแนะนำเพิ่มเติม']
    };
  }

  // 5. น้ำท่วม / ไฟไหม้
  if (q.includes('น้ำท่วม') || q.includes('ไฟไหม้') || q.includes('จมน้ำ')) {
    return {
      reply: `สบายใจได้เลยค่ะ! สำหรับความคุ้มครอง **ภัยน้ำท่วมและไฟไหม้**:\n\n` +
        `🌊 **น้ำท่วม:** แผนประกันชั้น 1 ทุกแผน และแผน 2+ เกือบทั้งหมดในระบบของเรา คุ้มครองภัยน้ำท่วมเต็มทุนประกันค่ะ (เช่น ทุน 500,000 - 600,000 บาท จ่ายตามความเสียหายจริง สูงสุดตามทุนประกัน)\n\n` +
        `🔥 **ไฟไหม้:** คุ้มครองกรณีไฟไหม้ตัวรถจากทุกสาเหตุ ทั้งจากเครื่องยนต์ลัดวงจร หรือไฟไหม้ภายนอก\n\n` +
        `หากต้องการแผนที่เน้นทุนน้ำท่วมสูงเป็นพิเศษ สามารถเลือกดูแผนของ **วิริยะประกันภัย** หรือ **กรุงเทพประกันภัย** ได้เลยค่ะ`,
      suggestions: ['ดูแผนชั้น 1 คุ้มครองน้ำท่วม', 'ดูแผน 2+ คุ้มครองน้ำท่วม', 'เปรียบเทียบทุนประกัน']
    };
  }

  // 6. ซ่อมห้าง vs ซ่อมอู่
  if (q.includes('ซ่อมห้าง') || q.includes('ซ่อมอู่') || q.includes('ต่างกัน')) {
    return {
      reply: `ความแตกต่างระหว่าง **ซ่อมห้าง** กับ **ซ่อมอู่** สรุปง่ายๆ ดังนี้ค่ะ:\n\n` +
        `🏢 **ซ่อมห้าง (ซ่อมศูนย์):**\n` +
        `• ซ่อมกับศูนย์บริการมาตรฐานของยี่ห้อรถโดยตรง\n` +
        `• อะไหล่แท้เบิกศูนย์ 100% ช่างเชี่ยวชาญเฉพาะทาง\n` +
        `• เหมาะสำหรับรถใหม่ป้ายแดง หรือรถอายุ 1-5 ปี (เบี้ยจะสูงกว่าประมาณ 15-25%)\n\n` +
        `🔧 **ซ่อมอู่ในเครือ:**\n` +
        `• ซ่อมกับอู่มาตรฐานที่บริษัทประกันรับรองคุณภาพและรับประกันงานซ่อม\n` +
        `• สะดวก รวดเร็ว หาอู่ใกล้บ้านง่าย คิวรอซ่อมมักเร็วกว่าศูนย์\n` +
        `• เบี้ยประหยัดกว่า คุ้มค่าเงินมาก`,
      suggestions: ['แนะนำซ่อมห้าง', 'แนะนำซ่อมอู่', 'ขอดูเบี้ยทั้ง 2 แบบ']
    };
  }

  // 7. การผ่อนชำระ / ราคา
  if (q.includes('ผ่อน') || q.includes('จ่าย') || q.includes('บัตร') || q.includes('0%') || q.includes('ราคา') || q.includes('เบี้ย')) {
    return {
      reply: `เรื่องการชำระเงินสะดวกและยืดหยุ่นมากค่ะ 💳\n\n` +
        `• **ผ่อน 0% นานสูงสุด 6 - 10 เดือน** ผ่านบัตรเครดิตชั้นนำ (กสิกร, กรุงศรี, KTC, SCB, BBL, TTB)\n` +
        `• ชำระเต็มจำนวนผ่าน **QR Code / โอนเงิน / บัตรเครดิต**\n` +
        `• ได้รับความคุ้มครองทันที พร้อมรับกรมธรรม์อิเล็กทรอนิกส์ (e-Policy) ทาง SMS/Email\n\n` +
        `ต้องการให้คำนวณยอดผ่อนต่อเดือนของแผนไหนให้ดูไหมคะ?`,
      suggestions: ['คำนวณยอดผ่อนชั้น 1', 'คำนวณยอดผ่อน 2+', 'สนใจทำใบเสนอราคา']
    };
  }

  // 8. เอกสาร / ขั้นตอนการทำ
  if (q.includes('เอกสาร') || q.includes('สมัคร') || q.includes('ทำยังไง') || q.includes('ขั้นตอน') || q.includes('ใช้อะไร')) {
    return {
      reply: `ขั้นตอนการทำประกันง่ายมาก ใช้เอกสารเพียง 2 อย่างค่ะ:\n\n` +
        `📄 **เอกสารที่ต้องใช้:**\n` +
        `1. ภาพถ่ายหรือสำเนา **หน้าเล่มทะเบียนรถ** (หน้ารายการจดทะเบียน)\n` +
        `2. สำเนา **บัตรประชาชน** ของเจ้าของรถ\n` +
        `*(หากมีกรมธรรม์เดิม สามารถแนบมาเพื่อรับส่วนลดประวัติดีได้ค่ะ)*\n\n` +
        `📷 สามารถกดไอคอนรูปคลิปหนีบกระดาษด้านล่างเพื่ออัปโหลดรูปเอกสารได้ทันที ระบบจะอ่านข้อมูลรถให้อัตโนมัติค่ะ!`,
      suggestions: ['อัปโหลดหน้าเล่มทะเบียน', 'ติดต่อเจ้าหน้าที่', 'ดูแผนประกันต่อ']
    };
  }

  // 9. สนใจ / ติดต่อ / ทำใบเสนอราคา
  if (q.includes('สนใจ') || q.includes('ซื้อ') || q.includes('ตกลง') || q.includes('ติดต่อ') || q.includes('โทร') || q.includes('เสนอราคา')) {
    return {
      reply: `ยินดีเลยค่ะ! 🎉\n\n` +
        `หากต้องการให้เจ้าหน้าที่ผู้เชี่ยวชาญสรุป **ใบเสนอราคาพร้อมโปรโมชั่นพิเศษและของแถม** ส่งให้โดยตรง สามารถพิมพ์:\n` +
        `• ชื่อ-นามสกุล\n` +
        `• เบอร์โทรศัพท์ที่สะดวกรับสาย\n` +
        `• และช่วงเวลาที่สะดวกให้ติดต่อ\n\n` +
        `เจ้าหน้าที่จะติดต่อกลับเพื่อยืนยันเงื่อนไขและส่งกรมธรรม์ให้ทันทีค่ะ 😊`,
      suggestions: ['แจ้งเบอร์โทรให้ติดต่อกลับ', 'สอบถามเงื่อนไขเพิ่มเติม', 'ดูแผนอื่นๆ']
    };
  }

  // 10. Default Smart Response
  return {
    reply: `ขอบคุณสำหรับคำถามนะคะ 😊\n\n` +
      `${carPrefix}หากคุณต้องการสอบถามเกี่ยวกับ:\n` +
      `• เปรียบเทียบเบี้ยประกันและความคุ้มครอง (ชั้น 1 vs 2+ vs 3+)\n` +
      `• ข้อมูลบริษัทประกันยอดนิยม (วิริยะ, กรุงเทพ, ธนชาต, ทิพย, เมืองไทย)\n` +
      `• โปรโมชั่นส่วนลดกล้องหน้ารถ และการผ่อน 0%\n\n` +
      `สามารถพิมพ์บอกสิ่งที่ต้องการได้เลย หรือเลือกกดปุ่มตัวเลือกด้านล่างได้เลยค่ะ ยินดีดูแลเต็มที่ค่ะ!`,
    suggestions: ['ขอใบเสนอราคาชั้น 1', 'ขอใบเสนอราคา 2+', 'มีส่วนลดอะไรบ้าง?', 'ติดต่อเจ้าหน้าที่']
  };
}
