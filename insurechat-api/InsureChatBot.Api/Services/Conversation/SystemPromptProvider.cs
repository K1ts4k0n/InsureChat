        public string EffectiveSalesApproach() => Pick(_store.Get().SalesApproach, DefaultSalesApproach);
        public string EffectiveCompliance() => Pick(_store.Get().Compliance, DefaultCompliance);
        public string EffectiveStyle() => Pick(_store.Get().Style, DefaultStyle);

